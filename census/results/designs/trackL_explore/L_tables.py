"""EXPLORATORY tables (Track L, L2): every explored p = 0.8 setting at the proposed matched levels {0.6, 0.3, 0.03}‡.
Writes L_tables.md.  Usage (from census/): python results/designs/trackL_explore/L_tables.py"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import L_summary as S  # noqa: E402

FILES = ["explore_gate.jsonl", "explore_lever.jsonl", "explore_lever_adam.jsonl", "explore_probe.jsonl",
         "explore_tanh.jsonl", "explore_vsmall.jsonl"]
LEVELS = [0.6, 0.3, 0.03]

rows = S.load(FILES)
lines = ["# Track L exploration tables (EXPLORATORY; p = 0.8; generated by L_tables.py)", "",
         "Matched train-BCE levels {0.6, 0.3, 0.03}‡ (first check at or below; no interpolation). "
         "Δ = arm − std on the same seed, MNIST-randomised test accuracy (rand) and MNIST-reversed (rev); "
         "median (seeds up/down); cost = median per-seed ratio of steps to the level.", "",
         "## Standard arm: MNIST-randomised accuracy at each level (median over seeds)", "",
         "| setting | n | 0.6 | 0.3 | 0.03 | end |", "|---|---|---|---|---|---|"]
std = {}
for r in rows:
    if r["arm"] == "std" and r["p"] == 0.8:
        k = f"lr={r['lr']} w={r['width']} " + r.get("opt", "sgd") + ("" if r.get("act", "relu") == "relu" else "-" + r["act"]) \
            + ("" if r.get("vscale", 1.0) == 1.0 else f"-v{r['vscale']}")
        std.setdefault(k, []).append(r)
for k, rs in sorted(std.items()):
    vals = []
    for ell in LEVELS:
        x = [S.at(r["rec"], ell) for r in rs]
        x = [v["rand"] for v in x if v]
        vals.append(f"{np.median(x):.3f} ({len(x)})" if x else "—")
    lines.append(f"| {k} | {len(rs)} | " + " | ".join(vals) + f" | {np.median([r['rec']['rand'][-1] for r in rs]):.3f} |")
lines += ["", "## Paired differences vs std", "",
          "| setting, arm | n | Δrand 0.6 | Δrand 0.3 | Δrand 0.03 | Δrev 0.6 | Δrev 0.3 | Δrev 0.03 | cost 0.6 / 0.3 / 0.03 |",
          "|---|---|---|---|---|---|---|---|---|"]
pr = S.paired(rows, LEVELS)
for key, cell in pr.items():
    if not key.startswith("p=0.8"):
        continue
    f = lambda ell, q: (f"{cell[f'{ell}|{q}']['median']:+.4f} ({cell[f'{ell}|{q}']['up']}/{cell[f'{ell}|{q}']['down']})"
                        if cell[f"{ell}|{q}"]["n"] else "—")
    n = min(cell[f"{ell}|rand"]["n"] for ell in LEVELS)
    cost = " / ".join(f"×{cell[f'{ell}|cost']}" if cell[f"{ell}|cost"] else "—" for ell in LEVELS)
    lines.append(f"| {key[6:]} | {n} | " + " | ".join(f(e, "rand") for e in LEVELS) + " | "
                 + " | ".join(f(e, "rev") for e in LEVELS) + f" | {cost} |")
allmed = [abs(cell[f"{e}|rand"]["median"]) for key, cell in pr.items() if key.startswith("p=0.8") and " out" in key
          for e in LEVELS if cell[f"{e}|rand"]["n"]]
lines += ["", f"Largest |median Δrand| of any output-slowed arm at the three levels: {max(allmed):.4f}."]
(HERE / "L_tables.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
